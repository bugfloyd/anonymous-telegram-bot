// Regenerates data.ts from Unicode's emoji-test.txt: the emoji a keyboard
// offers, by category, in Unicode's order. Only emoji up to MAX_VERSION, so
// phones a few years old show them all (the app uses the phone's own emoji
// font), and only the default skin tone.
//
//   node web/src/emoji/make-data.mjs
//
// The source file is pinned by its SHA-256, so the output is the same every
// time.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://unicode.org/Public/emoji/15.1/emoji-test.txt';
const SHA256 = 'd876ee249aa28eaa76cfa6dfaa702847a8d13b062aa488d465d0395ee8137ed9';
const MAX_VERSION = 14.0;
const GROUPS = {
  'Smileys & Emotion': 'people',
  'People & Body': 'people',
  'Animals & Nature': 'nature',
  'Food & Drink': 'food',
  Activities: 'activity',
  'Travel & Places': 'travel',
  Objects: 'objects',
  Symbols: 'symbols',
  Flags: 'flags',
};
const SKIN_TONES = /[\u{1F3FB}-\u{1F3FF}]/u;

const text = await (await fetch(SOURCE)).text();
const hash = createHash('sha256').update(text).digest('hex');
if (hash !== SHA256) throw new Error(`emoji-test.txt changed: ${hash}`);

const out = new Map(Object.values(GROUPS).map((id) => [id, []]));
let group = null;
for (const line of text.split('\n')) {
  const g = line.match(/^# group: (.+)$/);
  if (g) {
    group = GROUPS[g[1]] ?? null;
    continue;
  }
  const m = line.match(/^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+) E(\d+\.\d+) /);
  if (!m || !group) continue;
  const [, emoji, version] = m;
  if (Number(version) > MAX_VERSION || SKIN_TONES.test(emoji)) continue;
  out.get(group).push(emoji);
}

const lines = [...out].map(([id, list]) => `  { id: '${id}', emoji: '${list.join(' ')}' },`);
writeFileSync(
  new URL('./data.ts', import.meta.url),
  `// Generated by make-data.mjs from Unicode's emoji-test.txt 15.1: emoji up to
// ${MAX_VERSION.toFixed(1)}, default skin tone, in Unicode's order. Don't edit by hand.
//
// Unicode data: © 2023 Unicode, Inc., under the Unicode License v3
// (https://www.unicode.org/license.txt).

/** A keyboard category and its emoji, separated by spaces. */
export interface EmojiGroup {
  id: 'people' | 'nature' | 'food' | 'activity' | 'travel' | 'objects' | 'symbols' | 'flags';
  emoji: string;
}

export const EMOJI_GROUPS: readonly EmojiGroup[] = [
${lines.join('\n')}
];
`,
);
